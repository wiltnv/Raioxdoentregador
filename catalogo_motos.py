def criar_moto_do_catalogo(moto_id: str, apelido: str, modelo_catalogo: str, hodometro_inicial: int) -> dict:
    tpl = CATALOGO_MOTOS[modelo_catalogo]
    pecas_novas = [dict(p, ultima_km=int(hodometro_inicial)) for p in tpl["pecas"]]
    return {
        "id": moto_id,
        "apelido": apelido.strip() or modelo_catalogo.split("(")[0].strip(),
        "modelo": modelo_catalogo,
        "tipo_posse": tpl.get("tipo_posse", "propria"),
        "hodometro": int(hodometro_inicial),
        "preco_gasolina": float(tpl["preco_gasolina"]),
        "consumo_kml": float(tpl["consumo_kml"]),
        "seguro_anual": float(tpl["seguro_anual"]),
        "seguro_mensal": float(tpl.get("seguro_mensal", 0.0)),
        "licenciamento_anual": float(tpl["licenciamento_anual"]),
        "aluguel_semanal": float(tpl.get("aluguel_semanal", 0.0)),
        "franquia_km_semanal": float(tpl.get("franquia_km_semanal", 0.0)),
        "km_excedente_valor": float(tpl.get("km_excedente_valor", 0.0)),
        "projecao_anual_km": float(tpl["projecao_anual_km"]),
        "pecas": pecas_novas
    }
